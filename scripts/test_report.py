"""Run the full test suite and record the result in docs/TEST_REPORT.md.

    python scripts/test_report.py            # or: make test-report
"""

from __future__ import annotations

import platform
import subprocess
import sys
import tempfile
import xml.etree.ElementTree as ET
from collections import defaultdict
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main() -> int:
    with tempfile.TemporaryDirectory() as tmp:
        junit = Path(tmp) / "junit.xml"
        proc = subprocess.run(
            [sys.executable, "-m", "pytest", "-q", "-p", "no:cacheprovider", f"--junitxml={junit}"],
            cwd=ROOT, capture_output=True, text=True,
        )
        suite = ET.parse(junit).getroot().find("testsuite")
    assert suite is not None

    per_file: dict[str, dict[str, int]] = defaultdict(lambda: defaultdict(int))
    durations: list[tuple[float, str]] = []
    failures: list[str] = []
    for case in suite.iter("testcase"):
        module = case.get("classname", "").split(".")
        path = "/".join(p for p in module if p.startswith("test") or p in ("unit", "integration", "e2e"))
        name = f"{path.split('/')[-1]}::{case.get('name')}"
        outcome = "passed"
        for tag in ("failure", "error", "skipped"):
            if case.find(tag) is not None:
                outcome = tag
        per_file[path][outcome] += 1
        durations.append((float(case.get("time", 0)), name))
        if outcome in ("failure", "error"):
            failures.append(name)

    commit = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=ROOT,
                            capture_output=True, text=True).stdout.strip()
    dirty = subprocess.run(["git", "status", "--porcelain", "dynamo", "tests"], cwd=ROOT,
                           capture_output=True, text=True).stdout.strip()
    total = int(suite.get("tests", 0))
    failed = int(suite.get("failures", 0)) + int(suite.get("errors", 0))
    lines = [
        "# Test report",
        "",
        "Generated by `python scripts/test_report.py`. Do not edit by hand.",
        "",
        "| | |",
        "|---|---|",
        f"| Date (UTC) | {datetime.now(timezone.utc):%Y-%m-%d %H:%M} |",
        f"| Commit | `{commit}`{' + uncommitted changes' if dirty else ''} |",
        f"| Python / OS | {platform.python_version()} / {platform.system()} {platform.release()} |",
        f"| Result | **{total - failed} passed, {failed} failed, {suite.get('skipped', 0)} skipped** "
        f"in {float(suite.get('time', 0)):.1f} s |",
        "",
        "## By file",
        "",
        "| File | Passed | Failed |",
        "|---|---:|---:|",
    ]
    for path in sorted(per_file):
        c = per_file[path]
        lines.append(f"| `{path}.py` | {c['passed']} | {c['failure'] + c['error']} |")
    lines += ["", "## Slowest tests", "", "| Seconds | Test |", "|---:|---|"]
    for seconds, name in sorted(durations, reverse=True)[:10]:
        lines.append(f"| {seconds:.2f} | `{name}` |")
    if failures:
        lines += ["", "## Failures", ""] + [f"- `{f}`" for f in failures]
    (ROOT / "docs" / "TEST_REPORT.md").write_text("\n".join(lines) + "\n")
    print(proc.stdout.strip().splitlines()[-1])
    return proc.returncode


if __name__ == "__main__":
    sys.exit(main())
